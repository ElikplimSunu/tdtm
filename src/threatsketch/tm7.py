"""Import Microsoft TMT `.tm7` models as Threat Dragon v2 JSON. SPEC section 11. PLAN task 4.2.

`import_tm7(path) -> (raw Threat Dragon JSON, warnings)`

- Each drawing surface becomes a STRIDE diagram. TMT GUIDs become cell ids, so generated threats
  get the same `sdl:<rule>:<flow guid>` keys TMT's own threats map to.
- What Threat Dragon cannot express goes into an `@tmt:` line in the description: the stencil ID
  when it is not the generic one, and every list attribute whose selection is not the first value.
- TMT's threats come along as threatsketch-tracked threats. Untouched ones (still AutoGenerated, no
  justification, never modified) get a normal fingerprint, so `analyze` sees them as its own.
  Anything triaged in TMT gets a fingerprint that never matches, so it is kept as a human edit.
"""

from __future__ import annotations

import re
import xml.etree.ElementTree as ET
from pathlib import Path

from . import __version__
from .merge import STRIDE_TYPES, fingerprint, merge, threat_id
from .td_adapter import Document

XSI_TYPE = "{http://www.w3.org/2001/XMLSchema-instance}type"
XSI_NIL = "{http://www.w3.org/2001/XMLSchema-instance}nil"
OUT_OF_SCOPE = "71f3d9aa-b8ef-4e54-8126-607a1d903103"  # TMT's fixed attribute names
OUT_OF_SCOPE_REASON = "752473b6-52d4-4776-9a24-202153f7d579"
DATAFLOW_ORDER = "15ccd509-98eb-49ad-b9c2-b4a2926d1780"
GUID = re.compile(r"[0-9a-f]{8}(-[0-9a-f]{4}){3}-[0-9a-f]{12}")
NODES = {  # GenericTypeId -> (Threat Dragon data.type, shape)
    "GE.P": ("tm.Process", "process"),
    "GE.EI": ("tm.Actor", "actor"),
    "GE.DS": ("tm.Store", "store"),
    "GE.TB.B": ("tm.BoundaryBox", "trust-boundary-box"),
}
EXTRA_PROPS = {  # Threat Dragon's own default properties per type (SPEC 2.3)
    "tm.Actor": {"providesAuthentication": False},
    "tm.Process": {
        "privilegeLevel": "",
        "isWebApplication": False,
        "handlesCardPayment": False,
        "handlesGoodsOrServices": False,
    },
    "tm.Store": {
        "isALog": False,
        "storesCredentials": False,
        "isEncrypted": False,
        "isSigned": False,
        "storesInventory": False,
    },
    "tm.Flow": {"protocol": "", "isEncrypted": False, "isPublicNetwork": False},
}
EDITED = "triaged in TMT"  # never a real sha1, so merge treats the threat as a human edit
UNTOUCHED = "0001-01-01"


class Tm7Error(ValueError):
    pass


def _local(tag: str) -> str:
    return tag.rsplit("}", 1)[-1]


def _kid(e: ET.Element, name: str) -> ET.Element | None:
    return next((c for c in e if _local(c.tag) == name), None)


def _text(e: ET.Element, name: str) -> str:
    k = _kid(e, name)
    return (k.text or "").strip() if k is not None else ""


def _xsi_type(e: ET.Element) -> str:
    return (e.get(XSI_TYPE) or "").rsplit(":", 1)[-1]


def _number(e: ET.Element, name: str) -> float | int:
    v = float(_text(e, name) or 0)
    return int(v) if v.is_integer() else v


def _dataflow_order(v: ET.Element) -> str | None:
    """TMT's Dataflow Order on flows and boundaries; None when it is the default "0"."""
    props = _kid(v, "Properties")
    for a in props if props is not None else []:
        if _text(a, "Name") == DATAFLOW_ORDER:
            return None if _text(a, "Value") in ("", "0") else _text(a, "Value")
    return None


def _read_properties(v: ET.Element) -> tuple[str, bool, str, list[str]]:
    """-> (name, out of scope, reason, `key=value` tag items for non-default selections)"""
    name, oos, reason, items = "", False, "", []
    props = _kid(v, "Properties")
    for a in props if props is not None else []:
        kind, display, key = _xsi_type(a), _text(a, "DisplayName"), _text(a, "Name")
        if kind == "StringDisplayAttribute" and display == "Name" and not key:
            name = _text(a, "Value")
        elif key == OUT_OF_SCOPE:
            oos = _text(a, "Value").lower() == "true"
        elif key == OUT_OF_SCOPE_REASON:
            reason = _text(a, "Value")
        elif kind == "ListDisplayAttribute":  # StaticList ones are implied by the stencil
            value = _kid(a, "Value")
            values = [(s.text or "").strip() for s in value] if value is not None else []
            index = int(_text(a, "SelectedIndex") or 0)
            if 0 < index < len(values):
                items.append(f"{display if GUID.fullmatch(key) else key}={values[index]}")
    return name, oos, reason, items


def _description(v: ET.Element, items: list[str]) -> str:
    type_id = _text(v, "TypeId")
    stencil = [type_id] if type_id and type_id != _text(v, "GenericTypeId") else []
    return "@tmt: " + "; ".join(stencil + items) if stencil or items else ""


def _line_style(oos: bool) -> dict:
    return {"stroke": "#333333", "strokeWidth": 1.5, "strokeDasharray": "4 3" if oos else ""}


def _keep(data: dict, values: dict) -> None:
    """Store TMT-only details under data['tdtm']['tm7'] so `export` can write them back."""
    values = {k: v for k, v in values.items() if v is not None}
    if values:
        data.setdefault("tdtm", {}).setdefault("tm7", {}).update(values)


def _node(v: ET.Element, z: int) -> dict | None:
    td_type, shape = NODES[_text(v, "GenericTypeId")]
    name, oos, reason, items = _read_properties(v)
    position = {"x": _number(v, "Left"), "y": _number(v, "Top")}
    size = {"width": _number(v, "Width"), "height": _number(v, "Height")}
    data = {"type": td_type, "name": name, "description": _description(v, items)}
    dash = _kid(v, "StrokeDashArray")
    _keep(
        data,
        {
            "strokeDashArray": None
            if dash is None or dash.get(XSI_NIL) == "true"
            else dash.text or "",
            "strokeThickness": _text(v, "StrokeThickness")
            if _text(v, "StrokeThickness") != "0"
            else None,
            "dataflowOrder": _dataflow_order(v),
        },
    )
    if td_type == "tm.BoundaryBox":
        data.update(isTrustBoundary=True, hasOpenThreats=False)
        return {
            "position": position,
            "size": size,
            "attrs": {"label": {"text": name}},
            "shape": shape,
            "zIndex": -1,
            "id": _text(v, "Guid"),
            "data": data,
        }
    data.update(outOfScope=oos, reasonOutOfScope=reason, isTrustBoundary=False)
    data.update(EXTRA_PROPS[td_type])
    data.update(hasOpenThreats=False, threats=[])
    attrs = {"text": {"text": name}}
    if td_type == "tm.Store":
        attrs.update(topLine=_line_style(oos), bottomLine=_line_style(oos))
    else:
        attrs["body"] = _line_style(oos)
    return {
        "position": position,
        "size": size,
        "attrs": attrs,
        "visible": True,
        "shape": shape,
        "zIndex": z,
        "id": _text(v, "Guid"),
        "data": data,
    }


def _end(v: ET.Element, side: str, ids: set[str]) -> dict:
    guid = _text(v, f"{side}Guid")
    if guid in ids:
        return {"cell": guid}
    return {"x": _number(v, f"{side}X"), "y": _number(v, f"{side}Y")}  # dangling end


def _line(v: ET.Element, z: int, ids: set[str]) -> dict:
    generic = _text(v, "GenericTypeId")
    name, oos, reason, items = _read_properties(v)
    # ponytail: TMT's middle handle becomes one vertex the line passes through. Close enough
    # for drawing and crossing tests; TMT draws a curve, its exact shape is not reproduced.
    vertices = (
        [{"x": _number(v, "HandleX"), "y": _number(v, "HandleY")}] if _text(v, "HandleX") else []
    )
    cell = {
        "shape": "flow",
        "width": 200,
        "height": 100,
        "zIndex": z,
        "connector": "smooth",
        "id": _text(v, "Guid"),
        "labels": [{"position": 0.5, "attrs": {"label": {"text": name}}}],
    }
    if generic == "GE.TB.L":  # [unverified]: no line boundary in the sample file
        cell.update(
            shape="trust-boundary-curve", attrs={"line": {"targetMarker": "", "sourceMarker": ""}}
        )
        cell["data"] = {
            "type": "tm.Boundary",
            "name": name,
            "description": _description(v, items),
            "isTrustBoundary": True,
            "hasOpenThreats": False,
        }
        cell["source"] = {"x": _number(v, "SourceX"), "y": _number(v, "SourceY")}
        cell["target"] = {"x": _number(v, "TargetX"), "y": _number(v, "TargetY")}
    else:
        cell["attrs"] = {
            "line": {
                **_line_style(oos),
                "targetMarker": {"name": "block"},
                "sourceMarker": {"name": ""},
            }
        }
        data = {
            "type": "tm.Flow",
            "name": name,
            "description": _description(v, items),
            "outOfScope": oos,
            "reasonOutOfScope": reason,
            "isTrustBoundary": False,
        }
        data.update(EXTRA_PROPS["tm.Flow"], isBidirectional=False, hasOpenThreats=False, threats=[])
        cell["data"] = data
        cell["source"], cell["target"] = _end(v, "Source", ids), _end(v, "Target", ids)
    if vertices:
        cell["vertices"] = vertices
    _keep(
        cell["data"],
        {
            "handle": [_number(v, "HandleX"), _number(v, "HandleY")],
            "ports": [_text(v, "PortSource"), _text(v, "PortTarget")],
            "source": [_number(v, "SourceX"), _number(v, "SourceY")],
            "target": [_number(v, "TargetX"), _number(v, "TargetY")],
            "dataflowOrder": _dataflow_order(v),
        },
    )
    return cell


def _nil_or_text(e: ET.Element, name: str) -> str | None:
    k = _kid(e, name)
    return None if k is None or k.get(XSI_NIL) == "true" else (k.text or "")


def _threat(v: ET.Element, position: int) -> tuple[str, dict]:
    """-> (flow guid, Threat Dragon threat)"""
    props = {}
    properties = _kid(v, "Properties")
    for kv in properties if properties is not None else []:
        props[_text(kv, "Key")] = _text(kv, "Value")
    flow, rule, state = _text(v, "FlowGuid"), _text(v, "TypeId"), _text(v, "State")
    category = props.get("UserThreatCategory", "")
    key = f"sdl:{rule}:{flow}"
    t = {
        "id": threat_id(key),
        "title": props.get("Title") or _text(v, "Title"),
        "status": {"Mitigated": "Mitigated", "NotApplicable": "NotApplicable"}.get(state, "Open"),
        "severity": _text(v, "Priority") or props.get("Priority") or "High",
        "type": next((s for s in STRIDE_TYPES.values() if s.lower() == category.lower()), category),
        "description": props.get("UserThreatDescription", ""),
        "mitigation": _text(v, "StateInformation"),
        "modelType": "STRIDE",
        "new": False,
        "number": int(_text(v, "Id") or 0),
        "score": "",
    }
    untouched = (
        state == "AutoGenerated"
        and not t["mitigation"]
        and _text(v, "ModifiedAt").startswith(UNTOUCHED)
    )
    t["tdtm"] = {
        "key": key,
        "fingerprint": fingerprint(t) if untouched else EDITED,
        "version": __version__,
    }
    if state == "NeedsInvestigation":  # no Threat Dragon status for it (SPEC 13)
        t["tdtm"]["tmtState"] = "Needs Investigation"
    modified = _text(v, "ModifiedAt")
    _keep(
        t,
        {
            "pos": position,
            "changedBy": _nil_or_text(v, "ChangedBy"),
            "interactionString": _nil_or_text(v, "InteractionString"),
            "modifiedAt": None if modified.startswith(UNTOUCHED) else modified,
            "state": state
            if state not in ("AutoGenerated", "Mitigated", "NotApplicable", "NeedsInvestigation")
            else None,
        },
    )
    return flow, t


def import_tm7(path: str | Path) -> tuple[dict, list[str]]:
    return parse_tm7(Path(path).read_bytes(), Path(path).stem, str(path))


def parse_tm7(data: bytes, title: str = "", path: str = "model") -> tuple[dict, list[str]]:
    """Like `import_tm7`, for bytes in memory. `title` names a model whose file holds none."""
    if b"<!DOCTYPE" in data[:4096] or b"<!ENTITY" in data:
        raise Tm7Error(f"{path}: refusing a .tm7 with a DOCTYPE or entities (not written by TMT)")
    try:
        root = ET.fromstring(data)
    except ET.ParseError as e:
        raise Tm7Error(f"{path}: not readable XML: {e}") from e
    if _local(root.tag) != "ThreatModel":
        raise Tm7Error(f"{path}: not a TMT model (root element {_local(root.tag)!r})")

    warnings: list[str] = []
    diagrams = []
    surfaces = _kid(root, "DrawingSurfaceList")
    for index, surface in enumerate(surfaces if surfaces is not None else []):
        cells, z = [], 0
        borders, lines = _kid(surface, "Borders"), _kid(surface, "Lines")
        border_values = [_kid(kv, "Value") for kv in (borders if borders is not None else [])]
        line_values = [_kid(kv, "Value") for kv in (lines if lines is not None else [])]
        for v in border_values:
            z += 1
            if _text(v, "GenericTypeId") in NODES:
                cells.append(_node(v, z))
            else:
                warnings.append(f"skipped {_text(v, 'GenericTypeId')} {_text(v, 'Guid')}")
        ids = {c["id"] for c in cells}
        for v in line_values:
            z += 1
            if _text(v, "GenericTypeId") in ("GE.DF", "GE.TB.L"):
                cells.append(_line(v, z, ids))
            else:
                warnings.append(f"skipped {_text(v, 'GenericTypeId')} {_text(v, 'Guid')}")
        diagrams.append(
            {
                "id": index,
                "title": _text(surface, "Header") or f"Diagram {index + 1}",
                "diagramType": "STRIDE",
                "placeholder": "New STRIDE diagram description",
                "thumbnail": "./public/content/images/thumbnail.stride.jpg",
                "version": "2.6.2",
                "cells": cells,
            }
        )

    meta = _kid(root, "MetaInformation")
    meta = meta if meta is not None else ET.Element("x")
    raw = {
        "version": "2.6.2",
        "summary": {
            "title": _text(meta, "ThreatModelName") or title,
            "owner": _text(meta, "Owner"),
            "description": _text(meta, "HighLevelSystemDescription"),
            "id": 0,
        },
        "detail": {
            "contributors": [
                {"name": n.strip()}
                for n in re.split(r"[;,\n]", _text(meta, "Contributors"))
                if n.strip()
            ],
            "diagramTop": len(diagrams),
            "reviewer": _text(meta, "Reviewer"),
            "threatTop": 0,
            "diagrams": diagrams,
        },
    }

    surface_keep = {}
    for index, surface in enumerate(surfaces if surfaces is not None else []):
        surface_keep[str(index)] = {"guid": _text(surface, "Guid"), "zoom": _text(surface, "Zoom")}
    raw["tdtm"] = {
        "tm7": {
            "version": _text(root, "Version"),
            "meta": {
                k: _text(meta, k)
                for k in ("Assumptions", "Contributors", "ExternalDependencies", "ThreatModelName")
            },
            "surfaces": surface_keep,
        }
    }
    doc = Document(raw, {c["id"]: c for d in diagrams for c in d["cells"]})
    instances = _kid(root, "ThreatInstances")
    unnumbered = []
    for position, kv in enumerate(instances if instances is not None else []):
        flow, t = _threat(_kid(kv, "Value"), position)
        cell = doc.cells.get(flow)
        if cell is None or cell["data"]["type"] != "tm.Flow":
            warnings.append(f"threat {t['number']} ({t['title']}) is on an unknown flow; skipped")
            continue
        cell["data"]["threats"].append(t)
        if t["number"] == 0:
            unnumbered.append(t)
        raw["detail"]["threatTop"] = max(raw["detail"]["threatTop"], t["number"])
    for t in unnumbered:  # TMT shows Id 0 as the next free Id, and keeps 0 in the file (SPEC 11)
        raw["detail"]["threatTop"] += 1
        t["number"] = raw["detail"]["threatTop"]
        _keep(t, {"id": 0})
    merge(doc, [], packs=())  # only restyles: hasOpenThreats and red outlines (SPEC 2.4)
    return raw, warnings
